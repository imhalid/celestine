// Builds the entry screen (Svelte) into one script and one stylesheet, and writes them as strings into
// ../landing.gen.js, which landing.js puts inline into the page (the page's CSP allows only its own nonce'd script).
//
//   node landing/build.mjs        (npm run build) before `wrangler dev` and before deploying; deploy.sh runs it
import { build } from "vite";
import { svelte } from "@sveltejs/vite-plugin-svelte";
import { readFileSync, readdirSync, writeFileSync, rmSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "dist");

await build({
  root: here,
  configFile: false,
  logLevel: "warn",
  plugins: [svelte()],
  build: {
    outDir: out,
    emptyOutDir: true,
    cssCodeSplit: false,
    minify: true,
    lib: { entry: join(here, "main.js"), formats: ["iife"], name: "celestineLanding", fileName: () => "landing.js" },
  },
});

const files = readdirSync(out);
const js = readFileSync(join(out, "landing.js"), "utf8");
const cssFile = files.find((f) => f.endsWith(".css"));
const css = cssFile ? readFileSync(join(out, cssFile), "utf8") : "";
rmSync(out, { recursive: true, force: true });

// put inline: neither may close its own element early
const safeJS = js.replace(/<\/script/gi, "<\\/script");
const safeCSS = css.replace(/<\/style/gi, "<\\/style");
writeFileSync(
  join(here, "..", "landing.gen.js"),
  `// Generated by landing/build.mjs from landing/*.svelte: do not edit.\nexport const LANDING_JS = ${JSON.stringify(safeJS)};\nexport const LANDING_CSS = ${JSON.stringify(safeCSS)};\n`,
);
console.log(`landing.gen.js: script ${(js.length / 1024).toFixed(1)} KB, style ${(css.length / 1024).toFixed(1)} KB`);
