// Builds the admin panel (admin/main.js, on synth-ui) into one ES module, beside the backend's WebAssembly, and
// writes them where the Worker takes them: ../admin.gen.js (the module as a string, and the path the module asks
// the WebAssembly from) and ../admin.bin (the WebAssembly, a Data module for the Worker).
//
//   node admin/build.mjs        (npm run build) before `wrangler dev` and before deploying; deploy.sh runs it
import { build } from "vite";
import { readFileSync, writeFileSync, rmSync, statSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "dist");

await build({
  root: here,
  configFile: false,
  logLevel: "warn",
  build: {
    outDir: out,
    emptyOutDir: true,
    minify: true,
    target: "es2022",
    lib: { entry: join(here, "main.js"), formats: ["es"], fileName: () => "app.js" },
  },
});

// A library build puts the WebAssembly into the module as a data: URL. It is taken out: the module asks for it
// beside itself instead (smaller, cached on its own, and the page's CSP needs no data:), and it is written as is.
let js = readFileSync(join(out, "app.js"), "utf8");
const inline = /new URL\("data:application\/wasm;base64,([A-Za-z0-9+/=]+)",\s*(?:"" \+ )?import\.meta\.url\)/;
const m = js.match(inline);
if (!m) throw new Error("admin/build.mjs: no WebAssembly in the module");
const wasm = Buffer.from(m[1], "base64");
// the names carry what is in them, so a page never gets a module with another's WebAssembly, and both can be cached for good
const hash = (b) => createHash("sha256").update(b).digest("hex").slice(0, 12);
const wasmPath = `synth-${hash(wasm)}.wasm`;
writeFileSync(join(here, "..", "admin.bin"), wasm);
js = js.replace(inline, `new URL(${JSON.stringify(wasmPath)}, import.meta.url)`);
const jsPath = `app-${hash(js)}.js`;
rmSync(out, { recursive: true, force: true });

writeFileSync(
  join(here, "..", "admin.gen.js"),
  `// Generated by admin/build.mjs from admin/*.js: do not edit.\nexport const ADMIN_JS = ${JSON.stringify(js)};\nexport const ADMIN_JS_PATH = ${JSON.stringify(jsPath)};\nexport const ADMIN_WASM_PATH = ${JSON.stringify(wasmPath)};\n`,
);
console.log(`admin.gen.js: script ${(js.length / 1024).toFixed(1)} KB; admin.bin: ${(statSync(join(here, "..", "admin.bin")).size / 1024).toFixed(0)} KB, served at /admin/${jsPath} and /admin/${wasmPath}`);
