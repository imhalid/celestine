func init() {
	for k, v := range enMore {
		if _, ok := enText[k]; !ok {
			enText[k] = v
		}
		if t := strings.TrimSuffix(k, ": "); t != k && t != "" {
			if _, ok := enText[t]; !ok {
				enText[t] = strings.TrimSuffix(v, ": ")
			}
		}
	}
}
